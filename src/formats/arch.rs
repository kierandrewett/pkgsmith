//! Arch Linux packages (`.pkg.tar.zst`): the files plus `.PKGINFO`, `.INSTALL` and `.MTREE`.

use super::ensure_resolved;
use crate::archive::{self, Compression, Leading};
use crate::hash::digests;
use crate::manifest::Manifest;
use crate::package::Package;
use crate::tree::{self, Data};
use crate::version::Version;
use anyhow::Result;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn architecture(arch: &str) -> &'static str {
    match arch {
        "amd64" => "x86_64",
        "arm64" => "aarch64",
        _ => "any",
    }
}

/// The body of a script as shell function text: the `#!` line and `set -e` go, because the function runs inside
/// pacman's own shell.
fn function(name: &str, script: &str) -> String {
    let body: Vec<&str> = script
        .lines()
        .filter(|l| !l.starts_with("#!") && l.trim() != "set -e")
        .collect();
    format!("{name}() {{\n{}\n}}\n", body.join("\n"))
}

fn pkginfo(package: &Package, version: &str) -> Result<String> {
    let manifest = package.manifest;
    let effective = &package.effective;
    ensure_resolved(&effective.depends, "depends")?;
    let mut text = String::from("# Generated by pkgsmith\n");
    let mut line = |key: &str, value: &str| {
        if !value.is_empty() {
            let _ = writeln!(text, "{key} = {value}");
        }
    };
    line("pkgname", &manifest.name);
    line("pkgbase", &manifest.name);
    line("pkgver", version);
    line("pkgdesc", package.summary());
    line("url", manifest.homepage.as_deref().unwrap_or(""));
    line("builddate", &package.options.mtime.to_string());
    line(
        "packager",
        manifest
            .arch_linux
            .packager
            .as_deref()
            .or(manifest.maintainer.as_deref())
            .unwrap_or("Unknown Packager"),
    );
    line("size", &package.installed_size().to_string());
    line("arch", architecture(&manifest.arch));
    line("license", manifest.license.as_deref().unwrap_or(""));
    for item in &effective.replaces {
        line("replaces", item);
    }
    for item in &effective.conflicts {
        line("conflict", item);
    }
    for item in &effective.provides {
        line("provides", item);
    }
    for item in &effective.depends {
        line("depend", item);
    }
    for item in effective.recommends.iter().chain(&effective.suggests) {
        line("optdepend", item);
    }
    for entry in package.entries.iter().filter(|e| e.config) {
        line("backup", entry.path.trim_start_matches('/'));
    }
    Ok(text)
}

/// `.MTREE`: size, time, mode and digests of every file, which `pacman -Qkk` checks later.
fn mtree(entries: &[tree::Entry], leading: &[Leading], mtime: u64) -> Result<String> {
    let mut text = String::from("#mtree\n/set type=file uid=0 gid=0 mode=644\n");
    for file in leading {
        let (md5, sha) = digests(&mut file.data.as_slice())?;
        let _ = writeln!(
            text,
            "./{} time={mtime}.0 size={} md5digest={md5} sha256digest={sha}",
            file.name,
            file.data.len()
        );
    }
    for entry in entries {
        let name = format!(".{}", entry.path);
        match &entry.data {
            Data::Ghost => {}
            Data::Dir => {
                let _ = writeln!(text, "{name} time={mtime}.0 mode={:o} type=dir", entry.mode);
            }
            Data::Symlink { target } => {
                let _ = writeln!(
                    text,
                    "{name} time={mtime}.0 mode=777 type=link link={target}"
                );
            }
            Data::File { src, size } => {
                let (md5, sha) = digests(&mut std::fs::File::open(Path::new(src))?)?;
                let _ = writeln!(
                    text,
                    "{name} time={mtime}.0 mode={:o} size={size} md5digest={md5} sha256digest={sha}",
                    entry.mode
                );
            }
        }
    }
    Ok(text)
}

/// `name-pkgver-release-arch.pkg.tar.zst`.
pub fn file_name(manifest: &Manifest) -> Result<String> {
    let version = format!(
        "{}-{}",
        Version::parse(&manifest.version)?.arch(),
        manifest.release
    );
    Ok(format!(
        "{}-{version}-{}.pkg.tar.zst",
        manifest.name,
        architecture(&manifest.arch)
    ))
}

pub fn build(package: &Package) -> Result<PathBuf> {
    let manifest = package.manifest;
    let version = format!(
        "{}-{}",
        Version::parse(&manifest.version)?.arch(),
        manifest.release
    );
    let mtime = package.options.mtime;

    let mut leading = vec![Leading {
        name: ".PKGINFO".into(),
        data: pkginfo(package, &version)?.into_bytes(),
        mode: 0o644,
    }];
    let scripts = &package.effective.scripts;
    let mut install = String::new();
    for (names, value) in [
        (&["pre_install", "pre_upgrade"][..], &scripts.pre_install),
        (&["post_install", "post_upgrade"][..], &scripts.post_install),
        (&["pre_remove"][..], &scripts.pre_remove),
        (&["post_remove"][..], &scripts.post_remove),
    ] {
        if let Some(script) = package.script(value)? {
            for name in names {
                install.push_str(&function(name, &script));
            }
        }
    }
    if !install.is_empty() {
        leading.push(Leading {
            name: ".INSTALL".into(),
            data: install.into_bytes(),
            mode: 0o644,
        });
    }
    let entries = tree::with_parents(&package.entries);
    let mtree_text = mtree(&entries, &leading, mtime)?;
    leading.push(Leading {
        name: ".MTREE".into(),
        data: Compression::Gzip.compress(mtree_text.as_bytes())?,
        mode: 0o644,
    });

    let tar = archive::tar(&entries, "", mtime, &leading)?;
    std::fs::create_dir_all(&package.options.out)?;
    let file = package.output(&file_name(manifest)?);
    std::fs::write(&file, Compression::Zstd.compress(&tar)?)?;
    Ok(file)
}
