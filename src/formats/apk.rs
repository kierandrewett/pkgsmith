//! Alpine packages (`.apk`, the version 2 format apk-tools 2 and 3 install).
//!
//! The file is three gzip streams that follow each other: the signature, the control part (`.PKGINFO` and the install
//! scripts) and the data part. The first two tars have no end marker, so a reader continues into the next stream.
//! `datahash` in `.PKGINFO` is the SHA-256 of the data stream. This writer does not sign, so install with
//! `apk add --allow-untrusted`.

use super::ensure_resolved;
use crate::archive::{self, Compression, Leading, TarStyle};
use crate::hash::hex;
use crate::manifest::Manifest;
use crate::package::Package;
use crate::tree;
use crate::version::Version;
use anyhow::Result;
use sha2::{Digest, Sha256};
use std::fmt::Write as _;
use std::path::PathBuf;

fn architecture(arch: &str) -> &'static str {
    match arch {
        "amd64" => "x86_64",
        "arm64" => "aarch64",
        _ => "noarch",
    }
}

fn pkginfo(package: &Package, version: &str, data_hash: &str) -> Result<String> {
    let manifest = package.manifest;
    let effective = &package.effective;
    for (field, list) in [
        ("depends", &effective.depends),
        ("provides", &effective.provides),
    ] {
        ensure_resolved(list, field)?;
    }
    let mut text = String::from("# Generated by pkgsmith\n");
    let mut line = |key: &str, value: &str| {
        if !value.is_empty() {
            let _ = writeln!(text, "{key} = {value}");
        }
    };
    line("pkgname", &manifest.name);
    line("pkgver", version);
    line("pkgdesc", package.summary());
    line("url", manifest.homepage.as_deref().unwrap_or(""));
    line("builddate", &package.options.mtime.to_string());
    line("packager", manifest.maintainer.as_deref().unwrap_or(""));
    line("size", &package.installed_size().to_string());
    line("arch", architecture(&manifest.arch));
    line("origin", &manifest.name);
    line("license", manifest.license.as_deref().unwrap_or(""));
    for item in &effective.replaces {
        line("replaces", item);
    }
    for item in &effective.provides {
        line("provides", item);
    }
    for item in &effective.depends {
        line("depend", item);
    }
    // apk writes a conflict as a dependency on the package with a leading "!".
    for item in &effective.conflicts {
        line("depend", &format!("!{item}"));
    }
    line("datahash", data_hash);
    Ok(text)
}

/// `name-version-rRELEASE.apk`.
pub fn file_name(manifest: &Manifest) -> Result<String> {
    Ok(format!(
        "{}-{}-r{}.apk",
        manifest.name,
        Version::parse(&manifest.version)?.apk(),
        manifest.release
    ))
}

pub fn build(package: &Package) -> Result<PathBuf> {
    let manifest = package.manifest;
    let mtime = package.options.mtime;
    let version = format!(
        "{}-r{}",
        Version::parse(&manifest.version)?.apk(),
        manifest.release
    );

    // The data stream first, because .PKGINFO holds its digest.
    let style = TarStyle {
        apk_checksums: true,
        open_ended: false,
    };
    let data_tar =
        archive::tar_styled(&tree::with_parents(&package.entries), "", mtime, &[], style)?;
    let data = Compression::Gzip.compress(&data_tar)?;
    let data_hash = hex(&Sha256::digest(&data));

    let mut control_files = vec![Leading {
        name: ".PKGINFO".into(),
        data: pkginfo(package, &version, &data_hash)?.into_bytes(),
        mode: 0o644,
    }];
    let scripts = &package.effective.scripts;
    for (names, value) in [
        (&[".pre-install", ".pre-upgrade"][..], &scripts.pre_install),
        (
            &[".post-install", ".post-upgrade"][..],
            &scripts.post_install,
        ),
        (&[".pre-deinstall"][..], &scripts.pre_remove),
        (&[".post-deinstall"][..], &scripts.post_remove),
    ] {
        if let Some(text) = package.script(value)? {
            for name in names {
                control_files.push(Leading {
                    name: (*name).into(),
                    data: text.clone().into_bytes(),
                    mode: 0o755,
                });
            }
        }
    }
    let open = TarStyle {
        apk_checksums: false,
        open_ended: true,
    };
    let control_tar = archive::tar_styled(&[], "", mtime, &control_files, open)?;
    let control = Compression::Gzip.compress(&control_tar)?;

    let mut file = control;
    file.extend(data);
    std::fs::create_dir_all(&package.options.out)?;
    let path = package.output(&file_name(manifest)?);
    std::fs::write(&path, file)?;
    Ok(path)
}
