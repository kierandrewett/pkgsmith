//! Alpine packages (`.apk`, the version 2 format apk-tools 2 and 3 install).
//!
//! The file is three gzip streams that follow each other: the signature, the control part (`.PKGINFO` and the install
//! scripts) and the data part. The first two tars have no end marker, so a reader continues into the next stream.
//! `datahash` in `.PKGINFO` is the SHA-256 of the data stream. This writer does not sign, so install with
//! `apk add --allow-untrusted`.

use anyhow::Result;
use pkgsmith_plugin::archive::{self, Compression, Leading, TarStyle};
use pkgsmith_plugin::entry;
use pkgsmith_plugin::hash::hex;
use pkgsmith_plugin::version::Version;
use pkgsmith_plugin::{Host, Package, Scheme};
use sha2::{Digest, Sha256};
use std::fmt::Write as _;
use std::path::PathBuf;

fn architecture(arch: &str) -> &'static str {
    match arch {
        "amd64" => "x86_64",
        "arm64" => "aarch64",
        _ => "noarch",
    }
}

fn pkginfo(package: &Package, version: &str, data_hash: &str) -> Result<String> {
    let mut text = String::from("# Generated by pkgsmith\n");
    let mut line = |key: &str, value: &str| {
        if !value.is_empty() {
            let _ = writeln!(text, "{key} = {value}");
        }
    };
    line("pkgname", &package.name);
    line("pkgver", version);
    line("pkgdesc", package.summary());
    line("url", package.homepage.as_deref().unwrap_or(""));
    line("builddate", &package.mtime.to_string());
    line("packager", package.maintainer.as_deref().unwrap_or(""));
    line("size", &package.installed_size().to_string());
    line("arch", architecture(&package.arch));
    line("origin", &package.name);
    line("license", package.license.as_deref().unwrap_or(""));
    for item in &package.replaces {
        line("replaces", item);
    }
    for item in &package.provides {
        line("provides", item);
    }
    for item in &package.depends {
        line("depend", item);
    }
    // apk writes a conflict as a dependency on the package with a leading "!".
    for item in &package.conflicts {
        line("depend", &format!("!{item}"));
    }
    line("datahash", data_hash);
    Ok(text)
}

/// `name-version-rRELEASE.apk`.
pub fn file_name(package: &Package) -> Result<String> {
    Ok(format!(
        "{}-{}-r{}.apk",
        package.name,
        Version::parse(&package.version)?.apk(),
        package.release
    ))
}

pub fn build(package: &Package, host: &Host) -> Result<PathBuf> {
    let mtime = package.mtime;
    let version = format!(
        "{}-r{}",
        Version::parse(&package.version)?.apk(),
        package.release
    );

    // The data stream first, because .PKGINFO holds its digest.
    let style = TarStyle {
        apk_checksums: true,
        open_ended: false,
    };
    let data_tar = archive::tar_styled(
        &entry::with_parents(&package.entries),
        "",
        mtime,
        &[],
        style,
    )?;
    let data = Compression::Gzip.compress(&data_tar)?;
    let data_hash = hex(&Sha256::digest(&data));

    let mut control_files = vec![Leading {
        name: ".PKGINFO".into(),
        data: pkginfo(package, &version, &data_hash)?.into_bytes(),
        mode: 0o644,
    }];
    let scripts = &package.scripts;
    for (names, value) in [
        (&[".pre-install", ".pre-upgrade"][..], &scripts.pre_install),
        (
            &[".post-install", ".post-upgrade"][..],
            &scripts.post_install,
        ),
        (&[".pre-deinstall"][..], &scripts.pre_remove),
        (&[".post-deinstall"][..], &scripts.post_remove),
    ] {
        if let Some(text) = value {
            for name in names {
                control_files.push(Leading {
                    name: (*name).into(),
                    data: text.clone().into_bytes(),
                    mode: 0o755,
                });
            }
        }
    }
    let open = TarStyle {
        apk_checksums: false,
        open_ended: true,
    };
    let control_tar = archive::tar_styled(&[], "", mtime, &control_files, open)?;
    let control = Compression::Gzip.compress(&control_tar)?;

    // A signed package starts with a third stream: a tar with one member, `.SIGN.RSA256.KEYNAME.pub`, that holds an RSA
    // signature (SHA-256) of the bytes of the control stream. `apk` looks for a public key of that name in
    // /etc/apk/keys. KEYNAME is the file name of the private key, as `abuild` names its keys.
    let mut file = Vec::new();
    if host.can_sign(Scheme::RsaSha256) {
        let key = host
            .key_name(Scheme::RsaSha256)
            .ok_or_else(|| anyhow::anyhow!("the signing key has no name"))?;
        let signature = host.sign(Scheme::RsaSha256, &control)?;
        let member = Leading {
            name: format!(".SIGN.RSA256.{key}.pub"),
            data: signature,
            mode: 0o644,
        };
        let tar = archive::tar_styled(&[], "", mtime, &[member], open)?;
        file.extend(Compression::Gzip.compress(&tar)?);
    }
    file.extend(control);
    file.extend(data);
    std::fs::create_dir_all(&package.out)?;
    let path = package.output(&file_name(package)?);
    std::fs::write(&path, file)?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use pkgsmith_plugin::{Data, Entry};
    use std::collections::BTreeMap;
    use std::io::{Cursor, Read};
    use std::path::Path;

    const PROGRAM: &[u8] = b"#!/bin/sh\necho hi\n";
    /// Longer than the 100 bytes that a ustar header holds for a link target.
    const LONG_TARGET: &str = "/usr/share/hi/a-folder-with-a-long-name/and-another-long-folder-name/so-the-target-passes-100-bytes/file";

    fn entry(path: &str, data: Data, mode: u32) -> Entry {
        Entry {
            path: path.into(),
            data,
            mode,
            owner: "root".into(),
            group: "root".into(),
            config: false,
        }
    }

    /// A package with a program, an empty file, and symlinks: a plain one, one whose target has a `.` component that the
    /// tar crate drops, and one with a long target.
    fn sample(dir: &Path) -> Package {
        let program = dir.join("hi");
        std::fs::write(&program, PROGRAM).unwrap();
        let empty = dir.join("empty");
        std::fs::write(&empty, "").unwrap();
        let link = |target: &str| Data::Symlink {
            target: target.into(),
        };
        Package {
            format: "apk".into(),
            name: "hi".into(),
            version: "1.0.0".into(),
            release: "1".into(),
            arch: "amd64".into(),
            description: "Says hi".into(),
            entries: vec![
                entry(
                    "/usr/bin/hi",
                    Data::File {
                        src: program,
                        size: PROGRAM.len() as u64,
                    },
                    0o755,
                ),
                entry(
                    "/usr/share/hi/empty",
                    Data::File {
                        src: empty,
                        size: 0,
                    },
                    0o644,
                ),
                entry("/usr/bin/hello", link("/usr/bin/hi"), 0o777),
                entry("/usr/bin/hi-dot", link("/usr/bin/./hi"), 0o777),
                entry("/usr/bin/hi-long", link(LONG_TARGET), 0o777),
            ],
            mtime: 1_700_000_000,
            out: dir.join("out"),
            ..Default::default()
        }
    }

    /// The gzip streams of a package file, in order.
    fn streams(file: &[u8]) -> Vec<&[u8]> {
        let mut cursor = Cursor::new(file);
        let mut out = vec![];
        while (cursor.position() as usize) < file.len() {
            let start = cursor.position() as usize;
            flate2::bufread::GzDecoder::new(&mut cursor)
                .read_to_end(&mut Vec::new())
                .unwrap();
            out.push(&file[start..cursor.position() as usize]);
        }
        out
    }

    fn gunzip(stream: &[u8]) -> Vec<u8> {
        let mut out = vec![];
        flate2::read::GzDecoder::new(stream)
            .read_to_end(&mut out)
            .unwrap();
        out
    }

    /// A tar member as apk-tools 2 reads it (`apk_tar_parse` in `src/io_archive.c`).
    struct Member {
        path: String,
        kind: tar::EntryType,
        link: Option<String>,
        /// The records of the pax header right before the member.
        pax: BTreeMap<String, String>,
        body: Vec<u8>,
    }

    /// The members of a tar, read like apk-tools 2 does: a pax header gives the `path`, `linkpath` and checksum of the
    /// member after it, and a GNU long link header (type `K`) is skipped.
    fn members(tar_bytes: &[u8]) -> Vec<Member> {
        let mut archive = tar::Archive::new(tar_bytes);
        let mut pax = BTreeMap::new();
        let mut out = vec![];
        for entry in archive.entries().unwrap().raw(true) {
            let mut entry = entry.unwrap();
            let mut body = vec![];
            entry.read_to_end(&mut body).unwrap();
            let header = entry.header();
            match header.entry_type() {
                tar::EntryType::XHeader => {
                    for record in tar::PaxExtensions::new(&body) {
                        let record = record.unwrap();
                        pax.insert(
                            record.key().unwrap().to_owned(),
                            record.value().unwrap().to_owned(),
                        );
                    }
                }
                tar::EntryType::GNULongLink => {}
                kind => {
                    let text = |bytes: &[u8]| String::from_utf8(bytes.to_vec()).unwrap();
                    out.push(Member {
                        path: pax
                            .get("path")
                            .cloned()
                            .unwrap_or_else(|| text(&header.path_bytes())),
                        kind,
                        link: pax
                            .get("linkpath")
                            .cloned()
                            .or_else(|| header.link_name_bytes().map(|b| text(&b))),
                        pax: std::mem::take(&mut pax),
                        body,
                    });
                }
            }
        }
        out
    }

    fn sha1_hex(data: &[u8]) -> String {
        hex(&sha1::Sha1::digest(data))
    }

    /// The streams of the sample package: control, then data. It is not signed.
    fn sample_streams(dir: &Path) -> (Vec<Member>, Vec<u8>) {
        let file = std::fs::read(build(&sample(dir), &Host::silent()).unwrap()).unwrap();
        let streams = streams(&file);
        assert_eq!(streams.len(), 2, "control and data");
        (members(&gunzip(streams[0])), streams[1].to_vec())
    }

    fn find<'a>(members: &'a [Member], path: &str) -> &'a Member {
        members
            .iter()
            .find(|m| m.path == path)
            .unwrap_or_else(|| panic!("{path} is not in the tar"))
    }

    #[test]
    fn every_file_and_symlink_carries_the_sha1_that_apk_tools_2_checks() {
        // apk-tools 2 marks a package broken (`f:f` in its database, and `apk add` exits 1) when a member that is not a
        // folder or a device has no checksum. It hashes the bytes of a file and the target of a symlink (`need_checksum`
        // in src/database.c, `apk_fileinfo_get` in src/io.c).
        let dir = tempfile::tempdir().unwrap();
        let (_, data) = sample_streams(dir.path());
        let members = members(&gunzip(&data));
        for (path, bytes) in [
            ("usr/bin/hi", PROGRAM),
            ("usr/share/hi/empty", b"".as_slice()),
            ("usr/bin/hello", b"/usr/bin/hi".as_slice()),
            // The checksum is of the target as the archive holds it, which is what apk-tools finds on disk.
            ("usr/bin/hi-dot", b"/usr/bin/hi".as_slice()),
            ("usr/bin/hi-long", LONG_TARGET.as_bytes()),
        ] {
            let checksum = find(&members, path).pax.get("APK-TOOLS.checksum.SHA1");
            assert_eq!(checksum, Some(&sha1_hex(bytes)), "{path}");
        }
        for member in members.iter().filter(|m| m.kind.is_dir()) {
            assert!(member.pax.is_empty(), "{} has a pax header", member.path);
        }
    }

    #[test]
    fn a_link_target_longer_than_ustar_holds_reaches_apk_tools_2_whole() {
        // apk-tools 2 reads a long target from a pax `linkpath` record. It skips the GNU long link header, so a target
        // written that way is cut to what the ustar header holds.
        let dir = tempfile::tempdir().unwrap();
        let (_, data) = sample_streams(dir.path());
        let members = members(&gunzip(&data));
        let link = find(&members, "usr/bin/hi-long");
        assert!(link.kind.is_symlink());
        assert_eq!(link.link.as_deref(), Some(LONG_TARGET));
        assert_eq!(
            find(&members, "usr/bin/hello").link.as_deref(),
            Some("/usr/bin/hi")
        );
    }

    #[test]
    fn datahash_is_the_sha256_of_the_data_stream() {
        // apk-tools refuses the package when the data stream does not match `datahash` in `.PKGINFO`.
        let dir = tempfile::tempdir().unwrap();
        let (control, data) = sample_streams(dir.path());
        let pkginfo = String::from_utf8(find(&control, ".PKGINFO").body.clone()).unwrap();
        let datahash = pkginfo
            .lines()
            .find_map(|l| l.strip_prefix("datahash = "))
            .expect("a datahash line");
        assert_eq!(datahash, hex(&Sha256::digest(&data)));
    }

    #[test]
    fn the_same_package_gives_the_same_bytes() {
        let dir = tempfile::tempdir().unwrap();
        let mut package = sample(dir.path());
        let first = std::fs::read(build(&package, &Host::silent()).unwrap()).unwrap();
        package.out = dir.path().join("again");
        let second = std::fs::read(build(&package, &Host::silent()).unwrap()).unwrap();
        assert_eq!(first, second);
    }
}
